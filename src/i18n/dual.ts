export function useL() {
  const { i18n } = useTranslation();
  const en = i18n.language?.startsWith('en');
  return (enText: string, msText: string) => (en ? enText : msText);
}

export function useTx() {
  const { i18n } = useTranslation();
  const en = i18n.language?.startsWith('en');
  return (s?: string | null): string => {
    if (!s) return s ?? '';
    if (en) return s;
    return MS_DICT[s] ?? s;
  };
}

